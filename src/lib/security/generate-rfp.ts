export class ProtectedContentError extends Error {}

/**
 * Refuse a save that removes or rewords protected transparency content,
 * or that shrinks the engine Record. Called from saveProject (the single
 * write path) for security engine records only.
 *
 * NARROW by design: compares protected item ids and text against the
 * verdict already STORED on the record (never the incoming payload), so
 * a client cannot talk the guard out of anything, and ordinary edits
 * (question wording, weights, mandatory flags, new sections, deletions
 * of unprotected items) pass untouched. The thrown message names each
 * missing item so the buyer can restore it without losing other work;
 * the builder keeps unsaved edits on screen (saves are optimistic).
 */
export function assertEngineArtefactsIntact(existing: ProjectDetails, next: ProjectDetails): void {
  if (existing.engine !== "security_sourcing") return;

  // The Record is append-only (Article 9): verdicts and artefact
  // snapshots may grow, never shrink or mutate.
  const exV = existing.engine_data?.verdicts ?? [];
  const nxV = next.engine_data?.verdicts ?? [];
  if (nxV.length < exV.length) {
    throw new ProtectedContentError("The verdict record is append-only and cannot be shortened. Re-read the project (GET) and resubmit your edit on top of it.");
  }
  for (let i = 0; i < exV.length; i++) {
    if (nxV[i]?.version !== exV[i].version || nxV[i]?.input_digest !== exV[i].input_digest) {
      throw new ProtectedContentError("The verdict record is append-only and cannot be rewritten. Re-read the project (GET) and resubmit your edit on top of it.");
    }
  }
  const exA = existing.engine_data?.artefacts ?? [];
  const nxA = next.engine_data?.artefacts ?? [];
  if (nxA.length < exA.length) {
    throw new ProtectedContentError("Generated document versions are append-only and cannot be removed. Re-read the project (GET) and resubmit your edit on top of it.");
  }
  for (let i = 0; i < exA.length; i++) {
    if (nxA[i]?.version !== exA[i].version || nxA[i]?.input_digest !== exA[i].input_digest) {
      throw new ProtectedContentError("Generated document versions are append-only and cannot be rewritten. Re-read the project (GET) and resubmit your edit on top of it.");
    }
  }

  // Transparency items: only checked once a document has been generated.
  if (exA.length === 0) return;
  const stored = exV[exV.length - 1]?.verdict as SecurityScopeVerdict | undefined;
  if (!stored || !Array.isArray(stored.againstInterest)) return;

  const byId = new Map<string, { text: string; priority: string; sectionIncluded: boolean }>();
  for (const s of next.rfp_sections ?? []) {
    for (const q of s.questions) byId.set(q.id, { text: q.text, priority: q.priority, sectionIncluded: s.included });
  }
  const violations: string[] = [];
  for (const p of protectedTransparencyItems(stored)) {
    const found = byId.get(p.id);
    if (!found) violations.push(`"${p.text.slice(0, 70)}…" (${p.id}) was removed`);
    else if (found.text !== p.text) violations.push(`"${p.text.slice(0, 70)}…" (${p.id}) was reworded`);
    else if (!found.sectionIncluded) violations.push(`"${p.text.slice(0, 70)}…" (${p.id}) was hidden by excluding its section`);
  }
  if (violations.length) {
    throw new ProtectedContentError(
      `This save was refused because protected scoping transparency would be lost: ${violations.join("; ")}. ` +
      `Restore the listed items exactly as generated (your other edits are still in the editor and will save once restored). ` +
      `These records are constitutional (Articles 2, 6 and 14): annotate alongside them instead of editing them.`,
    );
  }
}
