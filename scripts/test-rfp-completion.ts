import assert from 'node:assert/strict';
import {reviewBriefFromFacts} from '../src/lib/current-buyer-facts';
import {draftResearch} from '../src/lib/draft-research';
import {analyticsProps} from '../src/lib/analytics-privacy';
import {getShortlistDataset} from '../src/lib/vendors';
import {fact} from './canonical-facts-fixture';
const facts=[fact('estate.sites',25),fact('estate.users',100),fact('constraints.timeline','Within six months')];
const handover=reviewBriefFromFacts(facts,'Secret Audit Ltd');
assert.ok(handover.outcome.length>=20,'confirmed scope must yield an editable handover, even without narrative intent');
assert.match(handover.outcome,/25 sites/);
assert.ok(!handover.outcome.includes('Secret Audit Ltd'));
assert.equal(reviewBriefFromFacts(facts.map(f=>({...f,struck:true})),'').outcome,'','removed facts must not return through fallback');
assert.equal(reviewBriefFromFacts(facts.map(f=>({...f,provenance:'inferred' as const})),'').outcome,'','unconfirmed facts must not become public wording');
const vendors=getShortlistDataset().slice(0,5).map(v=>({...v,regions:{...v.regions,uk_ireland:'yes' as const,europe:'unknown' as const},sectors:{...v.sectors,retail_ecommerce:'unknown' as const}}));
const one=draftResearch(vendors,'sase',{required_regions:['uk_ireland']});
assert.ok(one.considered>0);
assert.equal(draftResearch(vendors,'sase',{required_regions:['uk_ireland','europe']}).count,0,'all regions must pass, not just the first');
const sector=draftResearch(vendors,'sase',{required_regions:['uk_ireland'],sector:'retail_ecommerce'});
assert.equal(sector.count,0,'sector evidence gap is not a match');
assert.equal(sector.sectorUnconfirmed,one.count);
assert.equal(draftResearch(vendors,'sase',{required_regions:['uk_ireland'],required_features:['missing_capability']}).count,0);
assert.throws(()=>draftResearch(vendors,'invalid',{required_regions:['uk_ireland']}));
assert.throws(()=>draftResearch(vendors,'sase',{required_regions:[]}));
assert.deepEqual(analyticsProps({format:'docx',status:'ready',email:'private@example.test',reason:'storage',brief:'Private document'}),{format:'docx',status:'ready',reason:'storage'});
console.log('PASS: nonempty safe handover, removed/inferred fact exclusion, all-region and sector matching gates, capability exclusion, bounded analytics.');
