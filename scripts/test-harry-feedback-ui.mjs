import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'https://fixture.test/sase/shortlist/' });
for (const key of ['window', 'document', 'HTMLElement', 'HTMLFormElement', 'Event', 'CustomEvent', 'MutationObserver', 'Element']) globalThis[key] = dom.window[key];
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.requestAnimationFrame = cb => setTimeout(cb, 0);
globalThis.cancelAnimationFrame = clearTimeout;
window.requestAnimationFrame = globalThis.requestAnimationFrame;
window.cancelAnimationFrame = clearTimeout;
window.matchMedia = () => ({ matches: true });
HTMLElement.prototype.scrollIntoView = function () {};
const React = await import('react');
globalThis.React = React;
const { render, screen, fireEvent, waitFor, cleanup } = await import('@testing-library/react');
const { default: SourcingEntrance } = await import('../src/components/SourcingEntrance.tsx');
const { getShortlistDataset } = await import('../src/lib/vendors.ts');
const vendors = getShortlistDataset().slice(0, 2);
let calls = [];
let planError = false;
let requestError = false;
let matchingSlugs = [];
globalThis.fetch = async (url, options) => {
  const body = JSON.parse(options.body);
  calls.push({url, body});
  if (url.includes('/plan/')) {
    if (planError) throw new Error('Offline');
    return { ok: true, json: async () => ({ matches: matchingSlugs.map(slug=>({slug})), investigation: [{slug: vendors[0].slug, name: vendors[0].name, reasons: ['Retail sector evidence needs review.']}], outstanding_checks: ['Retail experience'] }) };
  }
  return { ok: !requestError, json: async () => requestError ? { error: 'Please try again.' } : { delivery: 'captured_not_sent' } };
};
const mount = () => render(React.createElement(SourcingEntrance, { vendors, features: [] }));
mount();
fireEvent.click(screen.getByRole('button', {name: /Review selected/}));
assert.ok(screen.getByText(/Select a provider and at least one request/));
assert.equal(calls.length, 0, 'empty review must not generate a plan or send a request');
fireEvent.change(screen.getByLabelText('Sector'), {target: {value: 'retail_ecommerce'}});
fireEvent.change(screen.getByLabelText('Business sites'), {target: {value: '25'}});
fireEvent.click(screen.getByRole('button', {name: 'Prepare my sourcing plan'}));
await waitFor(() => assert.ok(screen.getByText('We need to check some options for you')));
assert.ok(document.getElementById('sourcing-brief').hidden);
assert.ok(screen.getAllByRole('button', {name: 'Edit requirements'})[0]);
assert.ok(screen.getByText('Providers to investigate (1)'));
fireEvent.change(screen.getByLabelText('Anonymous supplier brief'), {target: {value: 'Buyer-reviewed anonymous brief'}});
fireEvent.click(screen.getAllByRole('checkbox', {name: /Include in proposals/})[0]);
fireEvent.click(screen.getByRole('button', {name: /Review selected/}));
await waitFor(() => assert.equal(document.activeElement.id, 'selected-requests-title'));
assert.ok(screen.getByRole('heading', {name: 'Selected providers and requests (1)'}));
fireEvent.change(screen.getByLabelText('Work email'), {target: {value: 'buyer@example.com'}});
fireEvent.click(screen.getByRole('checkbox', {name: /I ask Netify/}));
assert.equal(screen.getByRole('button', {name: 'Email my confirmation link'}).disabled, false);
fireEvent.click(screen.getAllByRole('button', {name: 'Edit requirements'})[0]);
assert.equal(document.getElementById('sourcing-brief').hidden, false);
assert.equal(screen.getByLabelText('Business sites').value, '25');
fireEvent.change(screen.getByLabelText('Business sites'), {target: {value: '26'}});
assert.equal(screen.getByRole('button', {name: 'Email my confirmation link'}).disabled, true, 'editing requirements must revoke consent');
fireEvent.click(screen.getByRole('button', {name: 'Prepare my sourcing plan'}));
await waitFor(() => assert.equal(calls.filter(c => c.url.includes('/plan/')).length, 2));
await waitFor(() => assert.equal(screen.getByRole('checkbox', {name: /I ask Netify/}).disabled, false));
assert.equal(screen.getByLabelText('Anonymous supplier brief').value, 'Buyer-reviewed anonymous brief', 'refresh must preserve manual brief edits');
assert.ok(screen.getByRole('heading', {name: 'Selected providers and requests (1)'}));
fireEvent.click(screen.getByRole('checkbox', {name: /I ask Netify/}));
fireEvent.click(screen.getByRole('button', {name: 'Email my confirmation link'}));
await waitFor(() => assert.ok(screen.getByText(/Preview test: confirmation captured/)));
const sent = calls.find(c => c.url.includes('/request/')).body;
assert.equal(sent.brief.sites, 26);
assert.equal(sent.brief.supplier_brief, 'Buyer-reviewed anonymous brief');
assert.equal(sent.recipients.length, 1);
assert.equal(sent.recipients[0].slug, vendors[0].slug);
assert.deepEqual(sent.recipients[0].actions, ['proposals']);
assert.equal(sent.consent, true);
assert.equal(sent.anonymous, true);
requestError = true;
fireEvent.click(screen.getByRole('button', {name: 'Email my confirmation link'}));
await waitFor(() => assert.ok(screen.getByText('Please try again.')));
assert.equal(screen.getByLabelText('Anonymous supplier brief').value, 'Buyer-reviewed anonymous brief');
cleanup();
planError = true;
mount();
fireEvent.click(screen.getByRole('button', {name: 'Prepare my sourcing plan'}));
await waitFor(() => assert.ok(screen.getByText(/Evidence matching is temporarily unavailable/)));
assert.ok(screen.getByLabelText('Anonymous supplier brief').value.includes('10 sites'));
assert.equal(screen.getByRole('checkbox', {name: /I ask Netify/}).disabled, false);
cleanup();
planError = false;
matchingSlugs = [vendors[0].slug];
mount();
fireEvent.click(screen.getByRole('button', {name: 'Prepare my sourcing plan'}));
await waitFor(() => assert.equal(document.querySelectorAll('article[id^="provider-"]').length, 1));
const providerAnchor = document.createElement('a');
providerAnchor.href = '#provider-' + vendors[1].slug;
providerAnchor.textContent = 'Fixture provider anchor';
document.body.append(providerAnchor);
fireEvent.click(providerAnchor);
await waitFor(() => assert.equal(document.querySelectorAll('article[id^="provider-"]').length, 2));
await waitFor(() => assert.equal(document.activeElement.id, 'provider-' + vendors[1].slug));
const formAnchor = document.createElement('a');
formAnchor.href = '#sourcing-brief';
formAnchor.textContent = 'Fixture form anchor';
document.body.append(formAnchor);
fireEvent.click(formAnchor);
await waitFor(() => assert.equal(document.getElementById('sourcing-brief').hidden, false));
await waitFor(() => assert.equal(document.activeElement.id, 'sourcing-requirement'));
providerAnchor.remove();
formAnchor.remove();
cleanup();
console.log('PASS component interactions: empty selections, plan transition, evidence gaps, focus, editing, preserved brief and recipients, revoked consent, request payload, request and matching failures');
