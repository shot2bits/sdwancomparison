import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import Directory from '../src/components/ShortlistProviderDirectory';
import content from '../data/shortlist-buyer-profiles.json';
import bt from '../data/bt-harry-overview.json';
const html=renderToStaticMarkup(<Directory vendors={content.profiles.map(p=>({slug:p.slug,name:p.name,category:p.role}))} selected={{'bt-business':['proposals']}} onChoose={()=>{}} onReview={()=>{}} reviewMessage="" />);
const text=bt.paragraphs.join(' ');
assert.equal(text.split(/\s+/).length,200);
assert.equal(bt.author,'Harry Yelland');
assert.equal(bt.provider_slug,'bt-business');
assert.equal(bt.profile_url,'https://netify.co.uk/marketplace/bt/');
assert(!text.includes('\u2014'));
assert.equal((html.match(/data-original-author="Harry Yelland"/g)||[]).length,1);
assert.equal((html.match(/class="buyer-profile"/g)||[]).length,30);
assert(html.includes('1 provider selected'));
const btHtml=html.split('id="provider-bt-business"')[1].split('<details')[0];
assert(btHtml.includes('Include in proposals'));
assert(btHtml.includes('https://netify.co.uk/marketplace/bt/'));
const escape=(s:string)=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&#x27;');
for(const p of bt.paragraphs)assert(btHtml.includes(escape(p)),'Original paragraph missing from SSR');
console.log('PASS BT exact 200-word original excerpt, 30 SSR profiles, full-profile link and sourcing selection retained.');
