import assert from 'node:assert/strict';
import {getShortlistDataset} from '../src/lib/vendors';
import {editorialReviewStatus,providerEvidenceFingerprint,type ProviderEditorialReview} from '../src/lib/provider-editorial-review';
import {evidenceReviewHealth} from '../src/lib/evidence-review-health';
import {validateSourcingOperations} from './validate-sourcing-operations';
import {evidenceFingerprint,expiredEvidenceHeld} from '../src/lib/evidence-release-holds';
const v=getShortlistDataset()[0],now=Date.parse('2026-10-01');
const r:ProviderEditorialReview={buyer_fit:'Synthetic test only',strengths:['Test strength'],trade_offs:['Test limit'],source_urls:['https://example.com/evidence'],reviewer:'Synthetic test reviewer',role:'Test',approved_at:'2026-09-30',review_due:'2026-10-30',evidence_fingerprint:providerEvidenceFingerprint(v)};
assert.equal(editorialReviewStatus(v,r,now).status,'approved');
assert.equal(editorialReviewStatus({...v,last_verified:'2026-10-01'},r,now).status,'invalidated');
assert.equal(editorialReviewStatus(v,r,Date.parse('2026-10-31')).status,'expired');
assert.equal(editorialReviewStatus(v,{...r,reviewer:''},now).status,'invalid');
assert(evidenceReviewHealth(Date.parse('2026-10-20')).expiring>=23);
assert.throws(()=>validateSourcingOperations(Date.parse('2026-10-30T12:00:00Z'),'support@netify.com'),/Expired evidence/);
const heldNow=Date.parse('2026-10-31T12:00:00Z');
const health=validateSourcingOperations(heldNow,'support@netify.com');
assert.equal(health.expired,23);assert.equal(health.held_expired,23);assert.equal(health.unresolved_expired,0);
const record={review_due:'2026-10-30T00:00:00Z',source_urls:['https://example.com/retired']};
const registry={fixture:{fingerprint:evidenceFingerprint(record),held_at:'2026-10-31T00:00:00Z',reason:'Retired pending review'}};
assert(expiredEvidenceHeld('fixture',record,heldNow,registry));
assert(!expiredEvidenceHeld('new-record',record,heldNow,registry));
assert(!expiredEvidenceHeld('fixture',{...record,review_due:'2027-01-01'},heldNow,registry));
assert(!expiredEvidenceHeld('fixture',{...record,review_due:'invalid'},heldNow,registry));
assert(!expiredEvidenceHeld('fixture',record,Date.parse('2026-10-30T12:00:00Z'),registry));
assert(!expiredEvidenceHeld('fixture',record,heldNow,{fixture:{...registry.fixture,fingerprint:'changed'}}));
console.log('PASS exact expired records retired, runtime exclusion asserted, edited/new/future/invalid records cannot inherit a hold');
console.log('PASS invalidation, approval validity, expiry visibility and expired-evidence release gate');
