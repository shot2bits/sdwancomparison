import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import {withPlatformLoading,platformLoadingScript} from '../src/lib/platform-loading.ts';
const original=await readFile('preview/context-space/index.html','utf8');
const html=withPlatformLoading(original);
const dom=new JSDOM(html,{url:'https://netify.co.uk/marketplace/?core=new',runScripts:'outside-only'}),w=dom.window;
let timeout=()=>{};
w.setTimeout=((callback)=>{timeout=callback;return 1;});
w.eval(platformLoadingScript);
assert.equal(w.document.documentElement.hasAttribute('data-platform-ready'),false);
assert.equal(w.getComputedStyle(w.document.getElementById('netify-space')).visibility,'hidden');
assert.equal(w.document.getElementById('netify-platform-startup-message')?.textContent,'Loading your workspace…');
assert.equal(w.document.querySelectorAll('#ns-marketplace-h1').length,1,'Original content must remain intact');
timeout();
assert.equal(w.document.getElementById('netify-platform-retry')?.hidden,false);
assert.equal(w.document.getElementById('netify-platform-retry')?.getAttribute('href'),w.location.href);
assert.equal(w.document.documentElement.hasAttribute('data-platform-ready'),false,'A timeout must not expose the old screen');
const studio=w.document.createElement('section');studio.id='location-studio';
studio.innerHTML='<div id="ls-sector"><button>Retail</button></div><div id="ls-map" class="leaflet-container"></div><div id="ls-provider-top"><button>Provider</button></div>';
w.document.getElementById('netify-space').append(studio);
await Promise.resolve();
assert.equal(w.document.documentElement.hasAttribute('data-platform-ready'),false,'Wait for the pricing and project workspace to mount too');
const pricing=w.document.createElement('section');pricing.id='ns-pricing-workspace';studio.after(pricing);
await Promise.resolve();
assert.equal(w.document.documentElement.getAttribute('data-platform-ready'),'true');
assert.equal(w.document.getElementById('netify-platform-startup'),null);
assert.notEqual(w.getComputedStyle(w.document.getElementById('netify-space')).visibility,'hidden');
assert.equal(w.document.querySelectorAll('#ns-marketplace-h1').length,1);
dom.window.close();
console.log('PASS: slow startup hides the old screen; failure offers retry; full readiness reveals the unchanged workspace; retained content remains present.');
