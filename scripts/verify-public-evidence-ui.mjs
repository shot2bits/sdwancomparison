import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const dir = process.env.VERIFY_OUTPUT_DIR ?? '../publication-validation';
mkdirSync(dir,{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.VERIFY_BASE_URL ?? 'http://127.0.0.1:3177/sase';
const response=await page.goto(base+'/shortlist/',{waitUntil:'networkidle',timeout:120000});
assert.equal(response.status(),200);
await page.getByRole('heading',{name:'Provider, product and differentiator'}).waitFor();
const html=await page.content();
assert.ok(!html.includes('default_shortlist'));assert.ok(!/weighted capability score of \d/.test(html));
await page.screenshot({path:dir+'/shortlist-desktop.png',fullPage:true});
const data=await page.request.get(base+'/shortlist/data.json');const json=await data.json();
assert.equal(json.requires_publication,true);assert.equal(json.default_shortlist,undefined);
assert.equal(json.vendors.length,30);
const csv=await (await page.request.get(base+'/shortlist/data.csv')).text();
assert.ok(!csv.split('\r\n')[0].includes('"score"'));
await page.setViewportSize({width:390,height:844});
await page.goto(base+'/shortlist/',{waitUntil:'networkidle',timeout:120000});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'no horizontal page overflow');
await page.screenshot({path:dir+'/shortlist-mobile.png',fullPage:true});
await page.goto(base+'/alternatives/cato-networks/',{waitUntil:'networkidle',timeout:120000});
const alternatives=await page.locator('body').innerText();
assert.ok(!/No\. \d+ · Score/.test(alternatives));assert.ok(alternatives.includes('alphabetically'));
await page.screenshot({path:dir+'/alternatives-mobile.png',fullPage:true});
const chart=await page.request.get(base+'/shortlist/comparison-chart.png');assert.equal(chart.status(),200);
writeFileSync(dir+'/chart.png',await chart.body());
assert.deepEqual(errors,[]);
writeFileSync(dir+'/browser-checks.json',JSON.stringify({checked_at:new Date().toISOString(),public_evidence:true,desktop_mobile:true,chart_status:chart.status(),console_errors:errors},null,2));
await browser.close();
console.log('PASS browser desktop/mobile, hydration, JSON/CSV and evidence chart');
