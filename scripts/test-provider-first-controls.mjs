import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {enhanceProviderFirstEntrance} from '../preview/context-space/provider-first.js';
const html=await (await fetch('http://127.0.0.1:3017/providers/',{headers:{connection:'close'}})).text();
const dom=new JSDOM(html,{url:'http://127.0.0.1:3017/providers/?qa=unit-test'});
globalThis.document=dom.window.document;
dom.window.HTMLElement.prototype.scrollIntoView=function(){};
const calls=[],element=document.createElement('section');document.body.append(element);
enhanceProviderFirstEntrance({element,beginBrief:()=>calls.push('business'),openComparison:()=>calls.push('providers'),openRfp:()=>calls.push('rfp')});
const input=document.querySelector('#pf-provider-search');input.value='cato';input.dispatchEvent(new dom.window.Event('input'));
assert(document.querySelectorAll('[data-pf-row]:not([hidden])').length<30);
assert(!document.querySelector('[data-pf-row="cato-networks"]').hidden);
assert.equal(document.querySelectorAll('[data-pf-profile-record]').length,30,'Filtering must not drop evidence');
input.value='does-not-exist';input.dispatchEvent(new dom.window.Event('input'));
assert.equal(document.querySelector('#pf-no-matches').hidden,false);
document.querySelector('[data-pf-clear]').click();
assert.equal(document.querySelectorAll('[data-pf-row]:not([hidden])').length,30);
document.querySelector('[data-pf-profile="cato-networks"]').click();
assert(document.querySelector('#pf-provider-cato-networks').open);
document.querySelector('[data-pf-stage="business"]').click();
document.querySelector('[data-pf-stage="providers"]').click();
document.querySelector('[data-pf-stage="rfp"]').click();
assert.deepEqual(calls,['business','providers','rfp']);
document.querySelector('[data-pf-stage="catalogue"]').click();assert.equal(document.body.dataset.pfStage,'catalogue');
element.dispatchEvent(new dom.window.CustomEvent('provider-first:progress',{detail:{ready:true}}));
assert(document.querySelector('.pf-journey [data-pf-stage="business"]').classList.contains('pf-complete'));
element.dispatchEvent(new dom.window.CustomEvent('provider-first:progress',{detail:{ready:false}}));
assert(!document.querySelector('.pf-journey [data-pf-stage="business"]').classList.contains('pf-complete'));
console.log('PASS: search, empty state, reset, evidence expansion, stage navigation, catalogue return and progress state.');
